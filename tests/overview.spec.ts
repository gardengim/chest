import {test,expect} from '@playwright/test';
test('Overview shows available versions and news, folder is readonly, and cards retain bevels',async({page})=>{
  await page.addInitScript(()=>{
    const w=window as any;w.isTauri=true;
    const instance={id:'world',name:'World',version:'1.21.4',loader:'fabric',loader_version:'0.16.9',memory_mb:4096,java_path:'',artwork:'grass',installed:true};
    w.__TAURI_INTERNALS__={transformCallback:()=>1,invoke:async(name:string,args:any)=>{
      if(name==='get_config')return {instances:[instance],accounts:[],active_account:null,client_id:'',java_path:'',memory_mb:4096};
      if(name==='get_versions')return [{id:'26.3',type:'release'},{id:'1.21.4',type:'release'}];
      if(name==='get_fabric_versions')return ['0.16.10','0.16.9'];
      if(name==='get_instance_news')return {articles:[],unavailable:[]};
      if(name==='get_news')return Array.from({length:13},(_,index)=>({title:index?'Article '+index:'Minecraft update',date:'2026-10-01',url:'https://www.minecraft.net/article/update'}));
      if(name==='get_instance_icons')return {};
      if(name==='get_instance_folder')return '/tmp/World';
      if(name==='get_catalog_sources')return {modrinth:true,curseforge:false};
      if(name==='search_catalog')return {projects:[],total:0};
      if(name==='open_news'){w.__opened=args.url;return;}
      return [];
    }};
  });
  await page.goto('/');
  await expect(page.locator('.catalog-provider')).toHaveCount(0);
  expect(await page.locator('.home-explore').evaluate(node=>getComputedStyle(node).borderTopWidth)).toBe('0px');
  await expect(page.locator('.instance-icon img')).toHaveAttribute('src','/minecraft.png');
  await expect.poll(()=>page.locator('.instance-icon img').evaluate((node:HTMLImageElement)=>node.naturalWidth)).toBe(256);
  await expect(page.locator('.news-panel .news-item')).toHaveCount(6);
  await expect(page.locator('.news-source').first()).toHaveText('minecraft.net');
  const pagination=page.getByRole('navigation',{name:'News pages'});
  await expect(pagination.getByRole('button',{name:'Previous',exact:true})).toBeDisabled();
  await expect(pagination.getByRole('status')).toHaveText('1 / 3');
  await pagination.getByRole('button',{name:'Next',exact:true}).click();
  await expect(page.locator('.news-panel .news-item').first()).toContainText('Article 6');
  await expect(pagination.getByRole('status')).toHaveText('2 / 3');
  await pagination.getByRole('button',{name:'Next',exact:true}).click();
  await expect(page.locator('.news-panel .news-item')).toHaveCount(1);
  await expect(pagination.getByRole('button',{name:'Next',exact:true})).toBeDisabled();
  await pagination.getByRole('button',{name:'Previous',exact:true}).click();
  await expect(page.locator('.news-panel .news-item')).toHaveCount(6);
  expect(await page.locator('.instance-card').evaluate(node=>getComputedStyle(node,'::after').boxShadow)).not.toBe('none');
  await page.getByRole('button',{name:'World: Ready to play',exact:true}).click();
  await expect(page.locator('.news-panel .news-item')).toHaveCount(3);
  await page.getByRole('button',{name:'More',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'News'}).locator('.news-item')).toHaveCount(13);
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'More',exact:true})).toBeFocused();
  const updates=page.getByRole('region',{name:'Available updates'});
  await expect(updates).toContainText('Minecraft 26.3');
  await expect(updates).toContainText('Fabric 0.16.10');
  await page.getByRole('button',{name:/Minecraft update/}).click();
  expect(await page.evaluate(()=>(window as any).__opened)).toBe('https://www.minecraft.net/article/update');
  await page.getByRole('tab',{name:'Settings',exact:true}).click();
  await expect(page.getByLabel('Instance folder',{exact:true})).toHaveValue('/tmp/World');
  await expect(page.getByLabel('Instance folder',{exact:true})).toHaveAttribute('readonly','');
  await expect(page.getByRole('heading',{name:'Instance settings'})).toHaveCount(0);
  await expect(page.getByText('Remove this instance and its local files.')).toHaveCount(0);
  await page.getByRole('tab',{name:'Content',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Content',exact:true})).toHaveCount(0);
  await page.getByRole('tab',{name:'Log',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Log',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Chest home',exact:true}).click();
  await page.getByRole('button',{name:'World: Ready to play',exact:true}).click();
  await expect(page.getByRole('tab',{name:'Overview',exact:true})).toHaveAttribute('aria-selected','true');
});
